"""Quarantine config generation: turn a score threshold into an actionable pytest.ini."""

from __future__ import annotations

import pathlib
from dataclasses import dataclass, field

from .analysis import Analysis
from .errors import FlakyHunterError
from .stats import TestStats, flaky_tests

MARKER_NAME = "quarantine"
MARKER_DESCRIPTION = "flaky test excluded from CI until it is fixed"
MARKER_LINE = f"    {MARKER_NAME}: {MARKER_DESCRIPTION}"
MARKER_PREFIX = f"{MARKER_NAME}:"
ADDOPS_VALUE = '-m "not ' + MARKER_NAME + '"'
HEADER = "# Generated by flaky-hunter. Regenerate with: flaky-hunter quarantine <results>"


@dataclass(slots=True)
class QuarantinePlan:
    """The tests we would quarantine and how much CI time that saves."""

    tests: list[TestStats] = field(default_factory=list)
    threshold: float = 0.30
    total_failures: int = 0

    @property
    def estimated_saved_seconds(self) -> float:
        """Duration spent in runs that failed: that is the rerun cost we avoid."""
        return sum(item.total_duration * item.failure_rate for item in self.tests)


def plan(analysis: Analysis, threshold: float) -> QuarantinePlan:
    """Select tests at or above threshold that have both passing and failing runs."""
    chosen = flaky_tests(analysis.stats, threshold)
    chosen.sort(key=lambda s: (-s.score, s.test_id))
    return QuarantinePlan(
        tests=chosen,
        threshold=threshold,
        total_failures=sum(item.failures for item in chosen),
    )


def _existing_sections(lines: list[str]) -> list[str]:
    """Validate and return the pytest section header found in the file."""
    headers = [
        line.strip()
        for line in lines
        if line.strip().startswith("[") and line.strip().endswith("]")
    ]
    pytest_headers = [h for h in headers if h in ("[pytest]", "[tool:pytest]")]
    if headers and not pytest_headers:
        raise FlakyHunterError(
            "refusing to edit "
            + repr(headers[0])
            + " config: expected a [pytest] or [tool:pytest] section"
        )
    return pytest_headers


def render_ini(plan_result: QuarantinePlan, *, section: str = "[pytest]") -> str:
    """Render a fresh pytest.ini carrying the quarantine marker."""
    lines = [HEADER, section, "markers =", MARKER_LINE, "addopts = " + ADDOPS_VALUE, ""]
    if plan_result.tests:
        lines.append("; quarantined by flaky-hunter (score >= " + f"{plan_result.threshold:.2f})")
        for item in plan_result.tests:
            lines.append(";   " + f"{item.score:.2f}" + "  " + item.test_id)
    return "\n".join(lines) + "\n"


def _merge_addopts(existing: str) -> str:
    """Add our -m expression to an existing addopts value without clobbering flags."""
    value = existing.strip()
    if "not " + MARKER_NAME in value or "-m=" + repr("not " + MARKER_NAME) in value:
        return value
    if not value:
        return ADDOPS_VALUE
    return value + " " + ADDOPS_VALUE


def merge_ini(text: str, plan_result: QuarantinePlan) -> str:
    """Merge the quarantine marker into an existing pytest.ini, preserving its content."""
    lines = text.splitlines()
    _existing_sections(lines)
    if not any(line.strip() in ("[pytest]", "[tool:pytest]") for line in lines):
        lines = ["[pytest]"] + lines
    out: list[str] = []
    index = 0
    has_marker = any(line.strip().startswith(MARKER_PREFIX) for line in lines)
    has_addopts = False
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if stripped.startswith("[") and out and not has_marker:
            # Close the unterminated markers block before the next section starts.
            out.extend(["markers =", MARKER_LINE])
            has_marker = True
        if stripped.startswith("addopts") and "=" in stripped:
            key, value = stripped.split("=", 1)
            out.append(key.strip() + " = " + _merge_addopts(value))
            has_addopts = True
            index += 1
            continue
        out.append(line)
        index += 1
    if not has_marker:
        out.extend(["markers =", MARKER_LINE])
    if not has_addopts:
        out.append("addopts = " + ADDOPS_VALUE)
    body = "\n".join(out).rstrip() + "\n"
    if HEADER not in body:
        body = HEADER + "\n" + body
    return body


def write_ini(
    path: pathlib.Path, plan_result: QuarantinePlan, *, force: bool = False
) -> tuple[pathlib.Path, bool]:
    """Write or merge pytest.ini. Returns (path, created)."""
    target = path
    if target.exists() and target.is_dir():
        target = target / "pytest.ini"
    created = not target.exists()
    if not created and not force:
        text = target.read_text(encoding="utf-8", errors="replace")
        target.write_text(merge_ini(text, plan_result), encoding="utf-8")
        return target, False
    section = "[pytest]"
    if not created:
        text = target.read_text(encoding="utf-8", errors="replace")
        if "[tool:pytest]" in text:
            section = "[tool:pytest]"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_ini(plan_result, section=section), encoding="utf-8")
    return target, created


def render_terminal(plan_result: QuarantinePlan, path: pathlib.Path, created: bool) -> list[str]:
    """Human-readable summary of what quarantine decided."""
    lines = [
        "  quarantine threshold " + f"{plan_result.threshold:.2f}",
        "  "
        + str(len(plan_result.tests))
        + " test(s) selected, "
        + str(plan_result.total_failures)
        + " failing observations avoided",
    ]
    for item in plan_result.tests[:12]:
        lines.append("    " + f"{item.score:.2f}" + "  " + item.test_id)
    if len(plan_result.tests) > 12:
        lines.append("    ... " + str(len(plan_result.tests) - 12) + " more")
    lines.append("")
    lines.append("  " + ("created " if created else "updated ") + str(path))
    return lines
