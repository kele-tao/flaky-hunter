"""Quarantine generation and baseline diffing."""

from __future__ import annotations

import json

import pytest

from flaky_hunter.analysis import analyse_runs
from flaky_hunter.baseline import compare, load, save
from flaky_hunter.errors import FlakyHunterError
from flaky_hunter.model import Run, make_case
from flaky_hunter.quarantine import merge_ini, plan, render_ini, write_ini


def _analysis(flaky_names=("test_flaky",), stable=("test_ok",), runs=10):
    result = []
    for index in range(runs):
        run = Run(run_id=f"run-{index:03d}", ts=f"2026-01-{index + 1:02d}T09:00:00Z")
        for name in stable:
            case = make_case(
                run_id=run.run_id,
                ts=run.ts,
                classname="tests.test_a",
                name=name,
                outcome="pass",
                duration=1.0,
            )
            case.seq = index
            run.cases.append(case)
        for name in flaky_names:
            case = make_case(
                run_id=run.run_id,
                ts=run.ts,
                classname="tests.test_a",
                name=name,
                outcome="fail" if index % 2 else "pass",
                duration=2.0,
            )
            case.seq = index
            run.cases.append(case)
        result.append(run)
    return analyse_runs(result)


def test_plan_selects_only_above_threshold():
    analysis = _analysis()
    selected = plan(analysis, 0.2)
    assert [item.test_id for item in selected.tests] == ["tests/test_a.py::test_flaky"]
    assert selected.total_failures == 5
    assert selected.estimated_saved_seconds > 0


def test_plan_returns_empty_when_threshold_is_high():
    analysis = _analysis()
    assert plan(analysis, 0.99).tests == []


def test_render_ini_contains_marker_and_addopts():
    analysis = _analysis()
    text = render_ini(plan(analysis, 0.2))
    assert "[pytest]" in text
    assert "    quarantine: flaky test excluded from CI until it is fixed" in text
    assert 'addopts = -m "not quarantine"' in text


def test_render_ini_lists_selected_tests_as_comments():
    text = render_ini(plan(_analysis(), 0.2))
    assert ";   0." in text
    assert "tests/test_a.py::test_flaky" in text


def test_merge_ini_preserves_existing_settings():
    analysis = _analysis()
    existing = "[pytest]\naddopts = -q\ntestpaths = tests\n"
    merged = merge_ini(existing, plan(analysis, 0.2))
    assert "-q" in merged
    assert "not quarantine" in merged
    assert "testpaths = tests" in merged
    assert merged.startswith("# Generated by flaky-hunter")


def test_merge_ini_is_idempotent():
    analysis = _analysis()
    once = merge_ini("[pytest]\n", plan(analysis, 0.2))
    twice = merge_ini(once, plan(analysis, 0.2))
    assert twice.count("-m") == 1


def test_merge_ini_refuses_a_foreign_section():
    with pytest.raises(FlakyHunterError, match="refusing to edit"):
        merge_ini("[tool.black]\nline-length = 88\n", plan(_analysis(), 0.2))


def test_write_ini_creates_the_file(tmp_path):
    path, created = write_ini(tmp_path / "pytest.ini", plan(_analysis(), 0.2))
    assert created
    assert path.exists()
    assert "quarantine" in path.read_text(encoding="utf-8")


def test_write_ini_merges_by_default(tmp_path):
    target = tmp_path / "pytest.ini"
    target.write_text("[pytest]\naddopts = -q\n", encoding="utf-8")
    path, created = write_ini(target, plan(_analysis(), 0.2))
    assert not created
    assert "-q" in path.read_text(encoding="utf-8")


def test_write_ini_force_overwrites(tmp_path):
    target = tmp_path / "pytest.ini"
    target.write_text("[pytest]\naddopts = -q\n", encoding="utf-8")
    path, created = write_ini(target, plan(_analysis(), 0.2), force=True)
    assert not created  # the file existed; force replaced its content
    text = path.read_text(encoding="utf-8")
    assert "-q" not in text
    assert "not quarantine" in text


def test_write_ini_accepts_a_directory(tmp_path):
    path, created = write_ini(tmp_path, plan(_analysis(), 0.2))
    assert path.name == "pytest.ini"
    assert created


def test_baseline_round_trip(tmp_path):
    analysis = _analysis()
    path = tmp_path / "baseline.json"
    payload = save(path, analysis.stats)
    loaded = load(path)
    assert loaded["version"] == 1
    assert set(payload["tests"]) == set(loaded["tests"])


def test_compare_flags_newly_flaky_tests():
    from flaky_hunter.stats import TestStats

    stats = [TestStats(test_id="a", score=0.5, verdict="flaky", passes=5, failures=5)]
    diff = compare(stats, {"version": 1, "tests": {}})
    assert diff["newly_flaky"] == ["a"]
    assert diff["new_tests"] == ["a"]


def test_compare_flags_worsened_tests():
    from flaky_hunter.stats import TestStats

    stats = [TestStats(test_id="a", score=0.6, verdict="flaky", passes=4, failures=6)]
    diff = compare(stats, {"version": 1, "tests": {"a": {"score": 0.2, "verdict": "flaky"}}})
    assert diff["worsened"] == ["a"]


def test_compare_flags_fixed_tests():
    from flaky_hunter.stats import TestStats

    stats = [TestStats(test_id="a", score=0.0, verdict="stable", passes=20)]
    diff = compare(stats, {"version": 1, "tests": {"a": {"score": 0.5, "verdict": "flaky"}}})
    assert diff["fixed"] == ["a"]


def test_compare_reports_removed_tests():

    diff = compare([], {"version": 1, "tests": {"gone": {"score": 0.1, "verdict": "stable"}}})
    assert diff["removed"] == ["gone"]


def test_load_rejects_invalid_json(tmp_path):
    path = tmp_path / "baseline.json"
    path.write_text("{not json", encoding="utf-8")
    with pytest.raises(FlakyHunterError, match="not valid JSON"):
        load(path)


def test_load_rejects_payload_without_tests(tmp_path):
    path = tmp_path / "baseline.json"
    path.write_text(json.dumps({"version": 1}), encoding="utf-8")
    with pytest.raises(FlakyHunterError, match="no tests object"):
        load(path)
